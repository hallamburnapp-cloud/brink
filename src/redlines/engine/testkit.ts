/** A fresh game on the fixture pack. */
export function fixtureGame(seed = 'test'): GameState {
  return newGame(FIXTURE_CONTENT, seed);
}

/** A game with the given fields overwritten (shallow), for putting a state exactly where a test wants it. */
export function stateWith(patch: Partial<GameState>, seed = 'test'): GameState {
  return { ...fixtureGame(seed), ...patch };
}

/** The region ids the fixture lines cover, for tests that need a region on or off a line. */
export function lineRegions(id: string): RegionId[] {
  return FIXTURE_CONTENT.lines.find((l) => l.id === id)?.regions ?? [];
}
